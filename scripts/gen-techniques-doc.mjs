// Regenerates docs/TECHNIQUES.md from src/catalog.js (the single source of truth).
// Usage: node scripts/gen-techniques-doc.mjs
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { ROOT } from "../lib/config.js";
import { SITES, TECHNIQUE_IDS, buildLlamaEnv, buildOllamaOptions, describeTechnique, hill } from "../src/catalog.js";

const DOSES = [50, 150, 300, 500];
const out = [];
out.push("# Technique reference", "");
out.push("<!-- Generated by scripts/gen-techniques-doc.mjs from src/catalog.js. Do not edit by hand. -->", "");
out.push(
  "Each technique is a named bundle of runtime interventions. The drug-class name is a mnemonic for the *kind* of",
  "disturbance; what actually runs is the list of interventions below and the exact `LLM_INJ_*` values.",
  "",
  "Dose → intensity uses the Hill equation `E(d) = dⁿ / (EC50ⁿ + dⁿ)`; every engine parameter is linear in `E`.",
  "Intensity `E` is in [0, 1). `0 mg` always means *no intervention*.",
  "",
  "## Injection sites",
  "",
  "| Site | Where |",
  "|---|---|",
  ...Object.values(SITES).map((s) => `| ${s.label} | ${s.where} |`),
  "",
  "## Summary",
  "",
  "| Technique | Sites | EC50 (mg) | Hill n | Ollama |",
  "|---|---|---|---|---|"
);
for (const id of TECHNIQUE_IDS) {
  const d = describeTechnique(id);
  out.push(`| [${d.name}](#${id}) (\`${id}\`) | ${d.sites.join(", ") || "—"} | ${d.curve.ec50} | ${d.curve.n} | ${d.support.ollama} |`);
}
out.push("");
for (const id of TECHNIQUE_IDS) {
  const d = describeTechnique(id);
  out.push(`<a id="${id}"></a>`, `## ${d.name}`, "", `*${d.analogy}*`, "", d.summary, "", "**Interventions (llama.cpp):**", "");
  for (const m of d.mechanism) out.push(`- ${m}`);
  if (d.theme) out.push("", `Default theme words: ${d.theme.map((w) => `\`${w}\``).join(", ")} (override with the *theme* field).`);
  out.push("", "| Dose | E | Engine environment |", "|---|---|---|");
  for (const dose of DOSES) {
    const { env } = buildLlamaEnv(id, dose, { seed: 0, fixationIds: d.theme ? ["…"] : [] });
    delete env.LLM_INJ_SEED;
    const text = Object.entries(env).map(([k, v]) => `\`${k}=${v}\``).join("<br>") || "*(none)*";
    out.push(`| ${dose} mg | ${hill(dose, d.curve).toFixed(3)} | ${text} |`);
  }
  const o = buildOllamaOptions(id, 300, {});
  const ollamaText = !o
    ? "not available — this technique acts on model internals that Ollama does not expose."
    : !o.changes.length
      ? "identical to baseline."
      : `at 300 mg (default sampling): ${o.changes.map((c) => `\`${c.key}\` ${c.baseline} → ${c.treated}`).join(", ")}.`;
  out.push("", `**Ollama (${d.support.ollama}):** ${ollamaText}`, "");
}
await writeFile(path.join(ROOT, "docs", "TECHNIQUES.md"), `${out.join("\n")}\n`, "utf8");
console.log("wrote docs/TECHNIQUES.md");
